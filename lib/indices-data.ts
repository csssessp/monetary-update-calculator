// Mapeamento de nomes completos para nomes curtos usados no DB
const indiceNomesMap: { [key: string]: string } = {
  "IGP-M (FGV)": "IGP-M",
  "Poupança": "Poupança",
  "IPCA (IBGE)": "IPCA",
  "INPC (IBGE)": "INPC",
  "CDI": "CDI",
  "SELIC": "SELIC",
  "TR (Taxa Referencial)": "TR",
  "TR": "TR",
}

export function getIndiceNome(indiceCompleto: string): string {
  for (const key in indiceNomesMap) {
    if (indiceCompleto.includes(key)) {
      return indiceNomesMap[key]
    }
  }
  // Tenta match direto pela chave do banco de dados
  if ((indicesData as any)[indiceCompleto] !== undefined) return indiceCompleto
  return "IGP-M" // Fallback último recurso
}

// Helper: filtra dataset local por intervalo
function filtrarLocal(nome: string, startMonth?: number, startYear?: number, endMonth?: number, endYear?: number) {
  const arr: IndiceData[] = (indicesData as any)[nome] || []
  if (!arr.length) return []
  return arr.filter((i) => {
    const afterStart = !startMonth || !startYear || i.ano > startYear || (i.ano === startYear && i.mes >= startMonth)
    const beforeEnd = !endMonth || !endYear || i.ano < endYear || (i.ano === endYear && i.mes <= endMonth)
    return afterStart && beforeEnd
  })
}

// Helper: constrói querystring sem “undefined”
function buildQuery(params: Record<string, number | string | undefined>) {
  const sp = new URLSearchParams()
  Object.entries(params).forEach(([k, v]) => {
    if (v === undefined || v === null || (typeof v === "number" && !Number.isFinite(v))) return
    sp.set(k, String(v))
  })
  const qs = sp.toString()
  return qs ? `?${qs}` : ""
}

// Função auxiliar para buscar dados do banco de dados
async function fetchDB(name: string, startMonth?: number, startYear?: number, endMonth?: number, endYear?: number) {
  const qs = buildQuery({
    name: name,
    startMonth,
    startYear,
    endMonth,
    endYear,
  })
  const response = await fetch(`/api/indices${qs}`, { cache: "no-store" })
  if (!response.ok) return []
  const data = await response.json()
  if (!data?.success || !Array.isArray(data.indices)) return []

  const currentYear = new Date().getFullYear()
  const minYear = 1900 // Arbitrary minimum year for data validity

  return data.indices
    .map((item: any) => {
      // Garante que item é um objeto e tem as propriedades esperadas
      if (typeof item !== "object" || item === null || !("month" in item) || !("year" in item) || !("value" in item)) {
        console.warn("Item inválido recebido da API:", item)
        return null // Retorna null para itens inválidos
      }

      const mes = Number(item.month)
      const ano = Number(item.year)
      const valor = Number(item.value)

      // Validação rigorosa dos dados
      if (!Number.isFinite(mes) || mes < 1 || mes > 12) {
        console.warn("Mês inválido no item da API:", item)
        return null
      }
      if (!Number.isFinite(ano) || ano < minYear || ano > currentYear + 10) {
        console.warn("Ano inválido no item da API:", item)
        return null
      }
      if (!Number.isFinite(valor)) {
        console.warn("Valor inválido no item da API:", item)
        return null
      }

      return { mes, ano, valor }
    })
    .filter((item: IndiceData | null): item is IndiceData => item !== null) // Remove itens nulos
}

// Versão do formato/fonte dos índices guardados no localStorage
export const CHAVE_VERSAO_CACHE = "indices_cache_versao"
export const VERSAO_CACHE_INDICES = "2"

// Busca dados mesclando hardcoded local + localStorage (dados do BCB atualizados)
export async function obterIndicesAtualizados(
  nomeIndice: string,
  startMonth?: number,
  startYear?: number,
  endMonth?: number,
  endYear?: number,
): Promise<IndiceData[]> {
  const nomeCurto = getIndiceNome(nomeIndice)

  // 1. Dados hardcoded locais (fallback confiável)
  const dadosLocais = filtrarLocal(nomeCurto, startMonth, startYear, endMonth, endYear)
  const mapa = new Map<string, IndiceData>()
  dadosLocais.forEach((d) => mapa.set(`${d.ano}-${d.mes}`, d))

  // 2. Poupança: ler do arquivo JSON persistente via API (dados sempre verificados)
  if (nomeCurto === "Poupança" && typeof window !== "undefined") {
    try {
      const resp = await fetch("/api/poupanca-indices", { cache: "no-store" })
      if (resp.ok) {
        const json = await resp.json()
        const entradas: IndiceData[] = Array.isArray(json.indices) ? json.indices : []
        entradas.forEach((d) => {
          if (typeof d.mes !== "number" || typeof d.ano !== "number" || typeof d.valor !== "number") return
          if (startMonth !== undefined && startYear !== undefined) {
            if (d.ano < startYear || (d.ano === startYear && d.mes < startMonth)) return
          }
          if (endMonth !== undefined && endYear !== undefined) {
            if (d.ano > endYear || (d.ano === endYear && d.mes > endMonth)) return
          }
          mapa.set(`${d.ano}-${d.mes}`, d)
        })
        console.log(`✓ Poupança: ${entradas.length} registros carregados do arquivo JSON`)
      }
    } catch (error) {
      console.warn("Poupança: falha ao ler API, usando dados estáticos locais", error)
    }
    // Limpar qualquer cache BCB antigo que possa ter ficado
    try { localStorage.removeItem("indices_Poupança") } catch { /* ignore */ }
  }

  // 3. Outros índices: mesclar com dados do localStorage (populados por atualizarIndicesNoCache)
  if (nomeCurto !== "Poupança" && typeof window !== "undefined") {
    try {
      const chave = `indices_${nomeCurto}`
      // Só aceita cache gravado pela versão atual (versões antigas guardavam o IGP-M arredondado da série 189)
      const stored = localStorage.getItem(CHAVE_VERSAO_CACHE) === VERSAO_CACHE_INDICES ? localStorage.getItem(chave) : null
      if (stored) {
        const dadosBCB: IndiceData[] = JSON.parse(stored)
        if (Array.isArray(dadosBCB)) {
          const hoje = new Date()
          let cutoffMonth = hoje.getMonth() + 1 - 24
          let cutoffYear = hoje.getFullYear()
          if (cutoffMonth <= 0) { cutoffMonth += 12; cutoffYear -= 1 }
          // CDI/SELIC do mês corrente são acumulados parciais — nunca usar
          const soMesesFechados = nomeCurto === "CDI" || nomeCurto === "SELIC"
          const mesCorrente = hoje.getFullYear() * 12 + hoje.getMonth() + 1
          dadosBCB.forEach((d) => {
            if (d && typeof d.mes === "number" && typeof d.ano === "number" && typeof d.valor === "number") {
              if (soMesesFechados && d.ano * 12 + d.mes >= mesCorrente) return
              const key = `${d.ano}-${d.mes}`
              if (startMonth !== undefined && startYear !== undefined) {
                if (d.ano < startYear || (d.ano === startYear && d.mes < startMonth)) return
              }
              if (endMonth !== undefined && endYear !== undefined) {
                if (d.ano > endYear || (d.ano === endYear && d.mes > endMonth)) return
              }
              const isHistorico = d.ano < cutoffYear || (d.ano === cutoffYear && d.mes < cutoffMonth)
              if (isHistorico && mapa.has(key)) return
              mapa.set(key, d)
            }
          })
          console.log(`✓ ${nomeCurto}: mesclados ${dadosBCB.length} registros do BCB com ${dadosLocais.length} locais`)
        }
      }
    } catch (error) {
      console.error(`Erro ao ler dados BCB do localStorage para ${nomeCurto}:`, error)
    }
  }

  const indicesAUsar = Array.from(mapa.values()).sort((a, b) => {
    if (a.ano !== b.ano) return a.ano - b.ano
    return a.mes - b.mes
  })

  if (indicesAUsar.length === 0) {
    console.warn(`Nenhum dado encontrado para ${nomeIndice}. Verifique se o índice existe em lib/indices-data.ts`)
  }

  return indicesAUsar
}

